const SESSION_KEY = "skinfit_intro_played_v1";

/**
 * Full-screen brand intro: navy screen -> "SkinFit" wipes in (left to right,
 * using the real logo geometry) -> "Wellness" pops in -> the whole lockup
 * hands off (via a shared layoutId) to its resting position in the page
 * behind it, which reveals simultaneously.
 */
export function LoginIntroSplash({ onDone }: { onDone: () => void }) {
  const [stage, setStage] = useState<"skinfit" | "wellness" | "leaving" | "gone">(
    "skinfit"
  );

  useEffect(() => {
    if (typeof window === "undefined") return;
    if (window.sessionStorage.getItem(SESSION_KEY)) {
      setStage("gone");
      onDone();
      return;
    }
    window.sessionStorage.setItem(SESSION_KEY, "1");

    const t1 = window.setTimeout(() => setStage("wellness"), 2100);
    const t2 = window.setTimeout(() => setStage("leaving"), 3500);
    const t3 = window.setTimeout(() => {
      setStage("gone");
      onDone();
    }, 5700);
    return () => {
      window.clearTimeout(t1);
      window.clearTimeout(t2);
      window.clearTimeout(t3);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  if (stage === "gone") return null;

  return (
    <motion.div
      className="fixed inset-0 z-[200] flex items-center justify-center bg-[#2C3E6B]"
      initial={{ opacity: 1 }}
      animate={{ opacity: stage === "leaving" ? 0 : 1 }}
      transition={{ duration: 1.1, ease: easeOut, delay: stage === "leaving" ? 0.4 : 0 }}
      onAnimationComplete={() => {
        if (stage === "leaving") setStage("gone");
      }}
    >
      <motion.div
        layoutId="app-logo"
        transition={{ duration: 1.4, ease: easeOut }}
        className="relative w-[min(80vw,20rem)] overflow-hidden"
      >
        <svg viewBox="130 240 560 135" className="w-full" fill="white" aria-hidden>
          <SkinFitPaths />
          <motion.g
            initial={{ opacity: 0, scale: 0.55 }}
            animate={
              stage === "wellness" || stage === "leaving"
                ? { opacity: 1, scale: 1 }
                : { opacity: 0, scale: 0.55 }
            }
            transition={{ type: "spring", stiffness: 160, damping: 15 }}
            style={{ transformBox: "fill-box", transformOrigin: "center" }}
          >
            <WellnessPaths />
          </motion.g>
        </svg>
        {/* Covering slab, same color as the splash background — slides off to
            the right, progressively uncovering the (always-rendered, already
            white) SkinFit wordmark underneath, left edge first. Percentage-based
            so the sweep always exactly clears the full width regardless of
            rendered size. */}
        <motion.div
          className="pointer-events-none absolute inset-y-0 left-0 w-full bg-[#2C3E6B]"
          initial={{ x: "0%" }}
          animate={{ x: "100%" }}
          transition={{ duration: 2, ease: easeOut }}
        />
      </motion.div>
    </motion.div>
  );
}
